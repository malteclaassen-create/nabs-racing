export function surfacesIni(): string {
  const lines: string[] = [
    '; Generated by AC Track Editor.',
    '; A mesh is physical when its name, ignoring the first character, starts',
    '; with one of the KEY values below. That is why every road mesh is called',
    '; 1ROAD_..., every kerb 1KERB_... and so on.',
    '',
  ];
  SURFACES.forEach((s, i) => {
    lines.push(
      `[SURFACE_${i}]`,
      `KEY=${s.key}`,
      `FRICTION=${s.friction}`,
      `DAMPING=${s.damping}`,
      `WAV=${s.wav}`,
      `WAV_PITCH=${s.wavPitch}`,
      'FF_EFFECT=NULL',
      `DIRT_ADDITIVE=${s.dirtAdditive}`,
      `IS_VALID_TRACK=${s.isValidTrack}`,
      `BLACK_FLAG_TIME=${s.blackFlagTime}`,
      `SIN_HEIGHT=${s.sinHeight}`,
      `SIN_LENGTH=${s.sinLength}`,
      `IS_PITLANE=${s.isPitlane}`,
      `VIBRATION_GAIN=${s.vibrationGain}`,
      `VIBRATION_LENGTH=${s.vibrationLength}`,
      '',
    );
  });
  return lines.join('\r\n');
}

/**
 * `circuit` is not decoration. It is the tag Content Manager reads to decide
 * what a track can be used FOR: without it, starting an ordinary race throws
 * "track won't work with selected mode: tag 'circuit' is missing" before the
 * session will load. The other two say who made the thing; this one says what
 * the thing is, and every Kunos track carries it.
 *
 * It goes on a point to point course as well as a lap. The tag means "an
 * ordinary racing track", as against the `drift` and `drag` tags that pick the
 * other game modes -- a hillclimb is raced in exactly the mode a circuit is.
 */
const TRACK_TAGS = ['circuit', 'custom', 'ac-track-editor'];

export function uiTrackJson(p: Project, lengthMetres: number, widthMetres: number, pitboxes: number): string {
  const data = {
    name: p.meta.name,
    description: p.meta.description,
    tags: TRACK_TAGS,
    geotags: [],
    country: p.meta.country,
    city: p.meta.city,
    length: String(Math.round(lengthMetres)),
    width: String(Math.round(widthMetres)),
    pitboxes: String(pitboxes),
    run: p.meta.run,
    author: p.meta.author,
    version: p.meta.version,
    url: '',
  };
  return JSON.stringify(data, null, 2);
}

export interface MapParams {
  width: number;
  height: number;
  margin: number;
  scaleFactor: number;
  xOffset: number;
  zOffset: number;
  drawingSize: number;
}

/**
 * The section is `[PARAMETERS]`, spelled out. It was `[PARAMS]` here, which is
 * what the format is usually CALLED, and Assetto Corsa does not know that name:
 * it looks up the section by string, finds nothing, and falls back to defaults.
 * The map then draws with the wrong scale and the car marker sits nowhere near
 * the circuit. Checked against Kunos' own files -- magione, ks_barcelona,
 * ks_highlands all read `[PARAMETERS]`.
 */
export function mapIni(m: MapParams): string {
  return [
    '[PARAMETERS]',
    `WIDTH=${m.width}`,
    `HEIGHT=${m.height}`,
    `MARGIN=${m.margin}`,
    `SCALE_FACTOR=${m.scaleFactor}`,
    `X_OFFSET=${m.xOffset}`,
    `Z_OFFSET=${m.zOffset}`,
    `DRAWING_SIZE=${m.drawingSize}`,
    '',
  ].join('\r\n');
}

/** Optional, only written when the track really is a single kn5 file. */
export function modelsIni(slug: string): string {
  return ['[MODEL_0]', `FILE=${slug}.kn5`, 'POSITION=0,0,0', 'ROTATION=0,0,0', ''].join('\r\n');
}

/**
 * What each flag panel state is: the flag id that switches it on, the colour
 * it lights in, and how fast it blinks.
 *
 * The ids are Assetto Corsa's own, listed in `flag_colors.lut` in the patch's
 * config folder: 1 green, 2 yellow, 12 blue, 15 session suspended. 0 -- no
 * flag at all, which is what a practice session hands out -- is taken as green
 * so the panels sit in their resting state rather than glowing blank white.
 *
 * A blinking yellow is not decoration. It is how a real panel says "this is
 * new" rather than "this is still on", and it is the one state a driver has to
 * pick up out of the corner of their eye at 250 km/h. Blue blinks for the same
 * reason. Green and red are steady, because they mean a condition rather than
 * an event.
 */
const FLAG_STATES = [
  { name: 'GREEN', ids: [0, 1], colour: '30, 220, 70', flashing: 0 },
  { name: 'YELLOW', ids: [2], colour: '255, 210, 30', flashing: 3 },
  { name: 'BLUE', ids: [12], colour: '40, 110, 255', flashing: 3 },
  { name: 'RED', ids: [15], colour: '255, 40, 30', flashing: 0 },
] as const;

/** Assetto Corsa reads its ini files as Windows text, so every line ends. */
const CRLF = '\r\n';

/** The highest flag id worth writing out. Above this AC has nothing to say. */
const FLAG_ID_MAX = 16;

/**
 * A condition's lookup table: 1 at the ids that switch it on, 0 everywhere.
 *
 * Every id is written out rather than only the interesting ones. A LUT
 * INTERPOLATES between the points it is given, so a table holding just the one
 * entry that matters reads as that value everywhere, and the panel shows
 * yellow for a green flag.
 */
function flagLut(ids: readonly number[]): string {
  const points: string[] = [];
  for (let i = 0; i <= FLAG_ID_MAX; i++) points.push(`${i}=${ids.includes(i) ? 1 : 0}`);
  return `LUT=(|${points.join('|')}|)`;
}

