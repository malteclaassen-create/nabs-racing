/**
 * The start gantry's lamps.
 *
 * This one cannot be done with conditions, and it took a working version to
 * see why. A track config's conditions read the time, the sun, the weather and
 * the FLAG, and that is the whole list -- so the best a config can say is "red
 * whenever no flag is showing". Which is right for the last few seconds before
 * a race and wrong for everything else: it also means red through the whole of
 * every practice session, and red through the entire wait on the grid, with
 * all five lamps on at once the whole time. Real start lights are dark until
 * the countdown and then come on ONE AT A TIME.
 *
 * A track script can see the countdown itself. `sim.timeToSessionStart` is the
 * milliseconds left before the green, which is exactly the number the sequence
 * is made of, and CSP has run Lua out of a track folder for years -- the SDK
 * ships definitions for it under `ac_track_script`, scoped to `content/tracks`
 * (see extension/internal/lua-sdk/rules.json in any patched install), and it is
 * loaded by a [SCRIPT_...] section in this very file.
 *
 * So the lamps are driven from Lua and there is no MATERIAL_ADJUSTMENT for
 * them at all. Two things writing the same three material properties every
 * frame is a race nobody wins.
 */
function startLightLines(): string[] {
  return [
    '',
    '; The five lights over the line, counted down by extension/start_lights.lua.',
    '[SCRIPT_...]',
    'ACTIVE = 1',
    `SCRIPT = ${START_LIGHTS_LUA}`,
  ];
}

/** Written next to ext_config.ini, which is where SCRIPT= looks for it. */
export const START_LIGHTS_LUA = 'start_lights.lua';

/**
 * The track script itself.
 *
 * Short on purpose. It runs every frame of every session on the circuit, so
 * the only thing it does per frame is work out a number from 0 to 5 and
 * compare it with the one it set last time.
 */
export function startLightsLua(): string {
  const columns = START_LIGHT_COLUMNS;
  return [
    '-- The start lights over the timing line. Written by AC Track Editor.',
    '--',
    '-- The gantry carries five columns of lamps as five separate meshes, which',
    '-- is the whole reason they are separate: they have to come on one at a',
    '-- time. See core/gantry.ts in the editor, which names them.',
    '',
    `local COLUMNS = ${columns}`,
    'local columns = {}',
    'for i = 1, COLUMNS do',
    '  -- ensureUniqueMaterials is not optional. A scene reference shares its',
    '  -- material with the rest of the scene until it is told not to, and all',
    '  -- five columns are one material in the model -- so without this, lighting',
    '  -- the first lamp lights all five and the sequence cannot be seen.',
    `  columns[i] = ac.findMeshes('${startLightMesh(1).replace(/1$/, '')}' .. i):ensureUniqueMaterials()`,
    'end',
    '',
    '-- Lit is exactly what the model bakes (EMISSIVE_MATERIAL_PROPS in the',
    "-- editor's kn5 writer); out is every term at zero, which is black glass.",
    '-- ksAmbient is the one that does the work: it is what draws a texture at',
    '-- its own brightness whatever the sun is doing.',
    'local function set(mesh, on)',
    "  mesh:setMaterialProperty('ksAmbient', on and 1.3 or 0)",
    "  mesh:setMaterialProperty('ksDiffuse', on and 0.12 or 0)",
    "  mesh:setMaterialProperty('ksEmissive', on and 1 or 0)",
    'end',
    '',
    'local shown = -1',
    'local function show(n)',
    '  if n == shown then return end',
    '  shown = n',
    '  for i = 1, COLUMNS do set(columns[i], i <= n) end',
    'end',
    '',
    '-- Dark on arrival, so a track standing empty is not lit up.',
    'show(0)',
    '',
    'function script.update(dt)',
    '  local sim = ac.getSim()',
    '  local lit = 0',
    '  if sim.raceSessionType == ac.SessionType.Race and not sim.isSessionStarted then',
    '    local left = sim.timeToSessionStart',
    '    -- -1 means the game has no countdown to report.',
    '    if left >= 0 and left < COLUMNS * 1000 then',
    '      -- One a second, so the fifth comes on with a second still to run and',
    '      -- they all go out together when the count reaches zero. Five is the',
    '      -- point: it is the number you can read at a glance from the grid.',
    '      lit = COLUMNS - math.floor(left / 1000)',
    '    end',
    '  end',
    '  show(math.max(0, math.min(COLUMNS, lit)))',
    'end',
    '',
  ].join('\r\n');
}

/**
 * The Custom Shaders Patch config that makes the flag panels follow the race.
 *
 * Written with the track whenever the barrier carries panels. None of the
 * machinery is invented here -- it is what the patch's own track configs do,
 * and the shape is lifted from two of them:
 *
 *   - A condition per state, INPUT=FLAG_TYPE through a lookup table, with
 *     FLASHING_FREQUENCY on the ones that blink. That is abu_dhabi_2021_chq's
 *     RACING_FLAG_YELLOW / _BLUE / _GREEN, and it is what makes a yellow
 *     actually flash rather than sit there.
 *   - A MATERIAL_ADJUSTMENT per state on the SAME material, each falling back
 *     to ORIGINAL when its own flag is not the one showing. Only one flag is
 *     ever up, so exactly one of them is driving the screen at a time.
 *   - One LIGHT_SERIES off the patch's own RACING_FLAG, which outputs the flag
 *     COLOUR rather than a switch, so the light the panels throw on the barrier
 *     after dark is the colour they are showing. CLUSTER_THRESHOLD is what
 *     keeps a lap's worth of them affordable.
 *
 * `common/conditions.ini` ships with the patch and is where RACING_FLAG comes
 * from; the four conditions below are ours, numbered high to stay clear of it.
 *
 * The material name is the editor's own key, because that is what the kn5
 * writer puts in the material table (see buildExport).
 */
export function extConfigIni(has: { flagPanels: boolean; startLights: boolean }): string {
  const lines: string[] = [
    '; Track wiring for Custom Shaders Patch, written by AC Track Editor.',
    '; Without CSP everything below is simply lit as it was modelled.',
    '',
    '[INCLUDE]',
    'INCLUDE = common/conditions.ini',
  ];

  if (has.startLights) lines.push(...startLightLines());
  if (!has.flagPanels) return lines.join(CRLF) + CRLF;

  FLAG_STATES.forEach((state, i) => {
    lines.push(
      '',
      `[CONDITION_${900 + i}]`,
      `NAME=FLAG_PANEL_${state.name}`,
      'INPUT=FLAG_TYPE',
      flagLut(state.ids),
      // Held for a moment and switched without delay: a flag that flickers
      // through a state on its way to another one is worse than no panel.
      'INPUT_STAY_FOR=1.0',
      'INPUT_CHANGE_DELAY=0',
    );
    if (state.flashing > 0) {
      lines.push(`FLASHING_FREQUENCY=${state.flashing}`, 'FLASHING_SMOOTHNESS=0.15', 'FLASHING_SYNCED=1');
    }
  });

  FLAG_STATES.forEach((state, i) => {
    lines.push(
      '',
      `[MATERIAL_ADJUSTMENT_${900 + i}]`,
      'ACTIVE = 1',
      `DESCRIPTION = flag panels, ${state.name.toLowerCase()}`,
      'MATERIALS = led_flag',
      'KEY_0 = ksEmissive',
      `VALUE_0 = ${state.colour}, 0.01`,
      'VALUE_OFF_0 = ORIGINAL',
      'KEY_1 = ksDiffuse',
      'VALUE_1 = 0',
      'VALUE_OFF_1 = ORIGINAL',
      `CONDITION = FLAG_PANEL_${state.name}`,
    );
  });

  lines.push(
    '',
    '[LIGHT_SERIES_900]',
    'ACTIVE = 1',
    'DESCRIPTION = the light the panels throw',
    'MATERIALS = led_flag',
    'OFFSET = 0,0,0',
    'DIRECTION = NORMAL',
    'SPOT = 150',
    'SPOT_SHARPNESS = 0.2',
    'RANGE = 6',
    'RANGE_GRADIENT_OFFSET = 0.2',
    'FADE_AT = 1000',
    'FADE_SMOOTH = 66',
    'DIFFUSE_CONCENTRATION = 0.5',
    'CLUSTER_THRESHOLD = 10',
    'COLOR = 255,255,255,0.01',
    'CONDITION = RACING_FLAG',
    '',
  );

  return lines.join('\r\n');
}
