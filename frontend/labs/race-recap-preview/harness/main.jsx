// Mounts the site's REAL race recap page (frontend/src/pages/
// RaceRecapPage.jsx, unchanged) inside the same frame the app gives it:
// the series provider, a router whose location carries the recap the way the
// app's recap host hands it over, and App.jsx's <main> wrapper. Only the API
// client is swapped (see vite.config.mjs and harness/mockClient.js).
import "./fonts.css"; // generated by build.mjs from the site's public/fonts/fonts.css
import "@site/index.css";
import React from "react";
import ReactDOM from "react-dom/client";
import { MemoryRouter, Navigate, Route, Routes } from "react-router-dom";
import { SeriesProvider } from "@site/context/SeriesContext.jsx";
// Variant C, "Race replay": a copy of the page with the replay player.
import RaceRecapPage from "./variants/replay/RaceRecapPage.jsx";
import { recap } from "./mockData.js";

// The site's default look is the dark theme in the classic design (index.html
// adds .dark before paint); this preview always uses it.
document.documentElement.classList.add("dark");
document.documentElement.removeAttribute("data-design");

const recapPath = `/s/${recap.race.seriesSlug || "nabs"}/recap/${recap.race.id}`;
// `pending` = the first visit after the round was saved: the page counts the
// arrival as seen and its last button reads "Carry on to the site".
const entry = { pathname: recapPath, state: { recap, pending: true } };

ReactDOM.createRoot(document.getElementById("root")).render(
  <React.StrictMode>
    <MemoryRouter initialEntries={[entry]} future={{ v7_startTransition: true, v7_relativeSplatPath: true }}>
      <SeriesProvider>
        <div className="flex min-h-screen flex-col">
          <main id="main" className="container-page min-h-screen w-full flex-1 py-6 sm:py-10">
            <div className="page-in">
              <Routes>
                <Route path="/s/:seriesSlug/recap/:raceId" element={<RaceRecapPage />} />
                {/* Links out of the recap (results, driver pages) have no page in
                    this preview: they come straight back to the recap. */}
                <Route path="*" element={<Navigate to={recapPath} replace state={{ recap, pending: true }} />} />
              </Routes>
            </div>
          </main>
          {/* Stands in for the site footer's height, so the last row of the
              page can still scroll far enough up the screen to reveal. */}
          <div aria-hidden="true" className="h-40 sm:h-48" />
        </div>
      </SeriesProvider>
    </MemoryRouter>
  </React.StrictMode>
);
