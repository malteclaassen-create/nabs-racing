// Builds the static recap preview into dist/:
//   1. regenerates the mock payloads (mock/build-mock.mjs)
//   2. writes harness/fonts.css (the site's self-hosted fonts, bundled by Vite)
//      and fills harness/public/ with only the pictures the page shows
//   3. runs the Vite build (vite.config.mjs)
//   4. turns dist/index.html into dist/page.html, the Artifact body (no
//      doctype/html/head/body: the host wraps it)
//
//   node build.mjs              build
//   node build.mjs --no-mock    keep mock/recap*.js as they are (hand-edited variants)
import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SITE_PUBLIC = join(HERE, "../../public"); // frontend/public
const HARNESS = join(HERE, "harness");
const PUB = join(HARNESS, "public");
const DIST = join(HERE, "dist");
const SITE_BG = "#080d18"; // --c-bg of html.dark in src/index.css

// The payload is a real round: mock/build-real.mjs turns the cached public API
// answers (api-cache/) into mock/real-recap.js. Nothing is fetched here.
if (!process.argv.includes("--no-mock")) {
  execFileSync(process.execPath, [join(HERE, "mock/build-real.mjs")], { stdio: "inherit" });
}

// --- fonts: the site links /fonts/fonts.css from index.html; here it is
// imported by the entry so Vite bundles the woff2 files into app/.
const fontsCss = readFileSync(join(SITE_PUBLIC, "fonts/fonts.css"), "utf8").replace(/url\(\/fonts\/([^)]+)\)/g, (_, f) => {
  const rel = relative(HARNESS, join(SITE_PUBLIC, "fonts", f)).split("\\").join("/");
  return `url(${rel})`;
});
writeFileSync(join(HARNESS, "fonts.css"), `/* GENERATED by build.mjs from frontend/public/fonts/fonts.css */\n${fontsCss}`);

// --- pictures: flags of every country in the mocks, the team logos the site
// has for the mocks' teams, the NABS Tokens mark.
rmSync(PUB, { recursive: true, force: true });
const copy = (from, to) => {
  const src = join(SITE_PUBLIC, from);
  if (!existsSync(src)) return false;
  mkdirSync(dirname(join(PUB, to)), { recursive: true });
  copyFileSync(src, join(PUB, to));
  return true;
};
const mocks = [];
for (const f of ["mock/real-recap.js"]) {
  if (existsSync(join(HERE, f))) mocks.push(await import(`${pathToFileURL(join(HERE, f)).href}?t=${Date.now()}`));
}
const countries = new Set();
const teams = new Set();
for (const { recap } of mocks) {
  countries.add(recap.race.country);
  const people = [
    ...recap.results,
    ...(recap.sprint?.results || []),
    ...(recap.quali || []),
    ...(recap.sprint?.quali || []),
    ...(recap.standings?.window || []),
    ...(recap.teammates || []),
    recap.card?.driver,
  ].filter(Boolean);
  for (const r of people) {
    if (r.country) countries.add(r.country);
    for (const t of [r.team, r.effectiveTeam, r.subForTeam]) if (t) teams.add(t);
  }
  if (recap.team) teams.add(recap.team);
}
for (const c of countries) for (const w of ["w40", "w80"]) copy(`flags/${w}/${c}.png`, `flags/${w}/${c}.png`);
// Team logos the payload points at under ./teams/ (the site's bundled ones).
for (const t of teams) {
  const m = /^\.\/teams\/([a-z0-9_]+\.png)$/.exec(t.logoUrl || "");
  if (m) copy(`teams/${m[1]}`, `teams/${m[1]}`);
}
// The few pictures from the live site's uploads that the page shows (fetched
// once into real-assets/ by a plain public GET, shrunk to display size).
const REAL_ASSETS = join(HERE, "real-assets");
for (const rel of ["uploads/avatars/maltegoat_s8.jpg", "uploads/avatars/pizd.png", "uploads/teams/s6_brawn_gp.png", "uploads/teams/s6_audi.png"]) {
  mkdirSync(dirname(join(PUB, rel)), { recursive: true });
  copyFileSync(join(REAL_ASSETS, rel), join(PUB, rel));
}
copy("nabs-star.webp", "nabs-star.webp");

// --- build
const { build } = await import("vite"); // resolved from frontend/node_modules
await build({ configFile: join(HERE, "vite.config.mjs") });

// --- dist/page.html: the head's stylesheet and module script, after a small
// head of our own; no document skeleton.
const index = readFileSync(join(DIST, "index.html"), "utf8");
const css = [...index.matchAll(/<link[^>]+rel="stylesheet"[^>]*>/g)].map((m) => m[0]);
const preload = [...index.matchAll(/<link[^>]+rel="modulepreload"[^>]*>/g)].map((m) => m[0]);
const script = index.match(/<script type="module"[^>]*><\/script>/)?.[0];
if (!css.length || !script) throw new Error("could not find the css link or module script in dist/index.html");
const page = [
  `<title>NABS Race Recap · ${mocks[0].recap.race.track}</title>`,
  `<meta name="theme-color" content="${SITE_BG}">`,
  `<style>:root{color-scheme:dark}html,body{background:${SITE_BG};margin:0}</style>`,
  ...css,
  ...preload,
  '<div id="root"></div>',
  script,
  "",
].join("\n");
writeFileSync(join(DIST, "page.html"), page);
// dist/index.html stays too, so `vite preview` can serve the build on localhost.
console.log(`dist/page.html written (${page.length} bytes)`);
